export function getVerifiedActivityDescription(
  slug: string,
  locale: PublicLocale,
  fallback: string,
) {
  const curatedContent = CONTENT[slug]?.[locale];
  if (!curatedContent) return fallback;

  const wordCount = fallback.trim().split(/\s+/u).filter(Boolean).length;
  const hasUnverifiedClaim = /(sertifikalı|certified production|sıfır hata|zero[- ]defect|maksimum güvenlik|maximum security|tam koruma|full protection|\bbr[2-7]\b|\bstanag\b|%\s*100|100%)/iu.test(fallback);

  // admin metni yeterli ve güvenliyse doğrudan onu kullanıyorum
  return wordCount >= 170 && !hasUnverifiedClaim
    ? fallback
    : curatedContent;
}
